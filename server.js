const SKIP_DIRS = new Set(['douyin-tool', 'node_modules', 'profile', '.git', 'android']);
const MEDIA_EXT = new Set(['.mp4', '.webp', '.gif', '.jpg', '.jpeg', '.png', '.mov', '.m4a', '.mp3', '.heic', '.zip']);

function walkFiles(dir, base, out, depth) {
  if (depth > 3) return out;
  let entries;
  try {
    entries = fs.readdirSync(dir, { withFileTypes: true });
  } catch (e) {
    return out;
  }
  for (const ent of entries) {
    const full = path.join(dir, ent.name);
    const rel = base ? base + '/' + ent.name : ent.name;
    if (ent.isDirectory()) {
      if (SKIP_DIRS.has(ent.name)) continue;
      walkFiles(full, rel, out, depth + 1);
    } else if (ent.isFile()) {
      if (!MEDIA_EXT.has(path.extname(ent.name).toLowerCase())) continue;
      try {
        const st = fs.statSync(full);
        out.push({ name: rel, size: st.size, mtime: st.mtimeMs });
      } catch (e) { /* skip */ }
    }
  }
  return out;
}

