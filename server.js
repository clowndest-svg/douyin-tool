async function exportCookies() {
  if (!context) return null;
  let cookies = [];
  try {
    cookies = await context.cookies();
  } catch (e) {
    return null;
  }
  if (!cookies.length) return null;
  const lines = ['# Netscape HTTP Cookie File', '# generated by douyin-tool', ''];
  for (const c of cookies) {
    const domain = c.domain || '';
    if (!domain) continue;
    const flag = domain.startsWith('.') ? 'TRUE' : 'FALSE';
    const secure = c.secure ? 'TRUE' : 'FALSE';
    const expires = c.expires && c.expires > 0 ? Math.floor(c.expires) : 0;
    lines.push([domain, flag, c.path || '/', secure, expires, c.name, c.value].join('\t'));
  }
  try {
    fs.writeFileSync(COOKIES_FILE, lines.join('\n') + '\n', 'utf8');
    return COOKIES_FILE;
  } catch (e) {
    return null;
  }
}

