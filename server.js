async function ensureBrowser() {
  lastBrowserUse = Date.now();
  if (context) {
    try {
      if (!page || page.isClosed()) page = context.pages()[0] || await context.newPage();
      return context;
    } catch (e) {
      context = null;
      page = null;
    }
  }
  const launchOptions = {
    headless: HEADLESS,
    viewport: HEADLESS ? { width: 1440, height: 900 } : null,
    userAgent: UA,
    args: [
      '--no-sandbox',
      '--disable-blink-features=AutomationControlled',
      '--disable-dev-shm-usage',
      '--disable-gpu',
      '--disable-software-rasterizer',
      '--renderer-process-limit=1',
      '--disable-extensions',
      '--no-default-browser-check',
    ],
    locale: 'zh-CN',
  };
  if (fs.existsSync(BUNDLED_CHROME)) {
    launchOptions.executablePath = BUNDLED_CHROME;
  } else if (IS_WIN) {
    launchOptions.channel = 'chrome';
  }
  context = await chromium.launchPersistentContext(PROFILE, launchOptions);
  context.on('close', () => { context = null; page = null; });
  try {
    await context.addInitScript(() => {
      Object.defineProperty(navigator, 'webdriver', { get: () => undefined });
    });
    page = context.pages()[0] || await context.newPage();
    page.on('close', () => { page = null; });
  } catch (e) {
    try { await context.close(); } catch (_) { /* ignore */ }
    context = null;
    page = null;
    throw e;
  }
  return context;
}

// 浏览器很吃内存（抖音一个页就 500MB+），空闲就关掉，登录态留在 profile 里
const BROWSER_IDLE_MS = (Number(process.env.BROWSER_IDLE_MIN) || 5) * 60000;
let lastBrowserUse = 0;
async function closeIdleBrowser() {
  if (!context) return;
  if (busy || downloadState.running || quarkState.running) return;
  if (Date.now() - lastBrowserUse < BROWSER_IDLE_MS) return;
  try { await context.close(); } catch (e) { /* 已经关了 */ }
  context = null;
  page = null;
  console.log(`[${new Date().toLocaleTimeString('zh-CN', { hour12: false })}] 浏览器空闲超 ${Math.round(BROWSER_IDLE_MS / 60000)} 分钟，已关闭释放内存（登录态存在 profile，下次自动复用）`);
}
setInterval(() => { closeIdleBrowser().catch(() => {}); }, 60000).unref();

